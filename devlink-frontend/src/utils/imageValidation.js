/**
 * Validates whether an image file is supported and within size limits.
 * @param {File} file
 * @param {number} maxSizeBytes - Default 5MB
 * @returns {{ valid: boolean, error?: string }}
 */
export const validateImageFile = (file, maxSizeBytes = 5 * 1024 * 1024) => {
  if (!file) return { valid: false, error: "No file selected." };

  if (!file.type || !file.type.startsWith("image/")) {
    return {
      valid: false,
      error: "Please select a valid image file (PNG, JPG, WebP, GIF, SVG).",
    };
  }

  if (file.size > maxSizeBytes) {
    const sizeInMb = (maxSizeBytes / (1024 * 1024)).toFixed(0);
    return {
      valid: false,
      error: `Image file size must be less than ${sizeInMb}MB.`,
    };
  }

  return { valid: true };
};

/**
 * Validates whether an image URL can be loaded and renders valid image data.
 * @param {string} url
 * @param {number} timeoutMs - Default 6000ms
 * @returns {Promise<{ valid: boolean, error?: string }>}
 */
export const validateImageUrl = (url, timeoutMs = 6000) => {
  return new Promise((resolve) => {
    if (!url || !url.trim()) {
      return resolve({ valid: true, empty: true });
    }

    const trimmed = url.trim();

    // Data URLs generated by FileReader
    if (trimmed.startsWith("data:image/")) {
      return resolve({ valid: true });
    }

    // Must be http or https
    if (!/^https?:\/\//i.test(trimmed)) {
      return resolve({
        valid: false,
        error: "Image URL must start with http:// or https://",
      });
    }

    const img = new Image();
    let hasFinished = false;

    const timer = setTimeout(() => {
      if (!hasFinished) {
        hasFinished = true;
        img.src = "";
        resolve({
          valid: false,
          error: "Image took too long to load. Please verify the URL or try another image.",
        });
      }
    }, timeoutMs);

    img.onload = () => {
      if (!hasFinished) {
        hasFinished = true;
        clearTimeout(timer);
        if (img.naturalWidth > 0 && img.naturalHeight > 0) {
          resolve({ valid: true });
        } else {
          resolve({
            valid: false,
            error: "The image at this URL appears to be broken or corrupted.",
          });
        }
      }
    };

    img.onerror = () => {
      if (!hasFinished) {
        hasFinished = true;
        clearTimeout(timer);
        resolve({
          valid: false,
          error: "Unable to load image from URL. Please check that the URL is public and direct.",
        });
      }
    };

    img.src = trimmed;
  });
};
